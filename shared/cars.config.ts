export const SHARED_CARS_CONFIG: SharedCarConfig[] = CAR_DRAFTS.map((draft) => {
  const glbSpec = SHARED_GLB_MODELS[draft.glbModelId];
  const basePi = estimateBasePi(
    draft.baseHp,
    draft.baseWeightKg,
    draft.tireGripMultiplier,
    draft.downforceScale,
    draft.drivetrain === 'AWD'
  );
  return {
    ...draft,
    glbUrl: glbSpec.localUrl,
    fallbackGlbUrl: glbSpec.remoteUrl,
    scale: glbSpec.scale,
    wheelNodeNames: glbSpec.wheelNodeNames,
    basePi,
    baseClass: classifyCarPi(basePi),
    priceCr: estimateCarPriceCr(basePi, draft.category, draft.baseHp),
  };
});

export function getSharedCarById(id: string): SharedCarConfig {
  return SHARED_CARS_CONFIG.find((c) => c.id === id) ?? SHARED_CARS_CONFIG[0];
}

