function estimateCarPriceCr(
  pi: number,
  category: string,
  hp: number
): number {
  const catMult =
    category === 'Hypercar' || category === 'EV Hypercar'
      ? 1.35
      : category === 'Supercar'
        ? 1.15
        : category === 'Track GT'
          ? 1.05
          : 0.9;
  const raw = ((pi - 520) * 320 + hp * 45) * catMult;
  return Math.max(35000, Math.round(raw / 1000) * 1000);
}

