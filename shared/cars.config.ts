export function classifyCarPi(pi: number): CarClass {
  if (pi >= 960) return 'X';
  if (pi >= 900) return 'S2';
  if (pi >= 800) return 'S1';
  if (pi >= 700) return 'A';
  return 'B';
}

function estimateBasePi(
  hp: number,
  weightKg: number,
  tireGripMult: number,
  downforceScale: number,
  isAwd: boolean
): number {
  const ptw = hp / (weightKg / 1000);
  const raw =
    430 +
    ptw * 0.48 +
    (tireGripMult - 0.9) * 140 +
    downforceScale * 48 +
    (isAwd ? 24 : 0);
  return Math.round(Math.max(580, Math.min(999, raw)));
}

